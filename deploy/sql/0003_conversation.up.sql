-- Conversation metadata and per-user watermarks. Both are hash-partitioned by
-- owner/uid (16 partitions) as required by ZIM-01 §9.3.

CREATE TABLE IF NOT EXISTS zim_conversation (
    owner_id      BIGINT NOT NULL,
    conv_id       VARCHAR(64) NOT NULL,
    type          SMALLINT NOT NULL DEFAULT 1, -- 1 single 2 group
    peer_id       BIGINT NOT NULL DEFAULT 0,
    group_id      BIGINT NOT NULL DEFAULT 0,
    recv_opt      SMALLINT NOT NULL DEFAULT 0,
    is_pinned     SMALLINT NOT NULL DEFAULT 0,
    burn_seconds  INT NOT NULL DEFAULT 0,
    deleted       SMALLINT NOT NULL DEFAULT 0,
    last_msg_id   VARCHAR(64),
    last_msg_seq  BIGINT NOT NULL DEFAULT 0,
    last_msg_at   BIGINT NOT NULL DEFAULT 0,
    last_msg_brief VARCHAR(255),
    updated_at    BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (owner_id, conv_id)
) PARTITION BY HASH (owner_id);

